#!/usr/bin/env bash
# ABOUTME: Brings the local stack into the suite #149 shape: the Graph API stub inside the backend's network namespace,
# ABOUTME: a compose override with canary secrets and the stub base URL, and a backend restart. Synthetic values only.
#
# Usage (from the repository root, after fixtures149.sh wrote out/ids):
#   stack149.sh up                      # stub + override + backend restart, outbound on
#   QA149_OUTBOUND=false stack149.sh up # same with the global kill switch off (P3-KILL-01, P3-KILL-10)
#   QA149_RATE=2 stack149.sh up         # same with a 2 per minute tenant send rate (P3-DUP-13)
#   stack149.sh stub                    # (re)start only the stub
#   stack149.sh down                    # stop the stub and restore the plain compose backend
set -euo pipefail
# The verify token is looked up by this reference name; the value itself lives in the local secret entries.
VERIFY_REF=qa149-verify
cd "$(git rev-parse --show-toplevel)"
QA149_DIR=${QA149_DIR:-docs/verification/issue-149-evidence}
OUTD=${OUTD:-$QA149_DIR/out}; STUBDIR=${STUBDIR:-$QA149_DIR/stub}; STUBBIN=${STUBBIN:-$OUTD/stub-bin}
OVERRIDE=$OUTD/compose.qa149.yaml
mkdir -p "$OUTD" "$STUBDIR" "$STUBBIN"
. "$OUTD/ids"

stub_up() {
  docker rm -f qa149-stub >/dev/null 2>&1 || true
  javac --release 26 -d "$STUBBIN" "$QA149_DIR/scripts/GraphStub.java"
  printf 'A=CANARY-TOKEN\nB=QA149-TOKEN-B-SYNTHETIC\n' > "$STUBDIR/tokens"
  printf '%s,%s' "$PN_A" "$PN_B" > "$STUBDIR/phones.list"
  printf 'customer_name,message_body' > "$STUBDIR/params"
  docker run -d --rm --name qa149-stub --network "container:$(docker compose ps -q oidc-bridge)" \
    -v "$(pwd)/$STUBDIR:/stub" -v "$(pwd)/$STUBBIN:/stub-bin:ro" eclipse-temurin:26-jre java -cp /stub-bin GraphStub >/dev/null
  sleep 1; docker logs qa149-stub 2>&1 | tail -1
}

write_override() {
  cat > "$OVERRIDE" <<EOF
# Generated by stack149.sh for suite #149. Every value is synthetic; the canaries exist to be searched for.
services:
  backend:
    environment:
      DOKENE_INTEGRATION_SECRETS_SOURCE: local
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_SCOPE: deployment
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_REF: qa149-app-secret
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_PURPOSE: APP_SECRET
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_VALUE: CANARY-APP-SECRET
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_SCOPE: deployment
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_REF: qa149-verify
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_PURPOSE: WEBHOOK_VERIFY_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_VALUE: CANARY-VERIFY
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_SCOPE: tenant
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_TENANT_ID: $A
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_REF: qa149-token-a
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_PURPOSE: WHATSAPP_ACCESS_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_VALUE: CANARY-TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_SCOPE: tenant
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_TENANT_ID: $B
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_REF: qa149-token-b
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_PURPOSE: WHATSAPP_ACCESS_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_VALUE: QA149-TOKEN-B-SYNTHETIC
      DOKENE_INTEGRATION_WHATSAPP_VERIFY_TOKEN_REF: ${VERIFY_REF}
      DOKENE_INTEGRATION_WHATSAPP_APP_SECRET_REF: qa149-app-secret
      DOKENE_INTEGRATION_WHATSAPP_GRAPH_BASE_URL: http://127.0.0.1:18080
      DOKENE_INTEGRATION_WHATSAPP_WEBHOOK_INBOX_INTERVAL: PT10S
      DOKENE_INTEGRATION_WHATSAPP_WEBHOOK_INBOX_PARK_WINDOW: PT1M
      DOKENE_MESSAGING_OUTBOUND_ENABLED: "${QA149_OUTBOUND:-true}"
      DOKENE_MESSAGING_SEND_RATE_PER_TENANT_PER_MINUTE: "${QA149_RATE:-30}"
      DOKENE_TEMPLATE_APPROVAL_MAX_AGE: "${QA149_TEMPLATE_MAX_AGE:-24h}"
      DOKENE_MESSAGING_RECOVERY_CLAIM_TIMEOUT: 2m
      DOKENE_MESSAGING_RECOVERY_INTERVAL: 20s
EOF
}

backend_wait() {
  local i; for i in $(seq 1 60); do
    [ "$(curl -s -o /dev/null -w '%{http_code}' http://localhost:8080/api/session || true)" = 401 ] && { echo "backend up after ${i}s"; return 0; }
    sleep 1
  done
  echo "backend did not come up" >&2; docker compose logs --no-color --tail 40 backend >&2; return 1
}

case ${1:-} in
  up) stub_up; write_override; docker compose -f compose.yaml -f "$OVERRIDE" up -d --no-build backend >/dev/null; backend_wait ;;
  restart) write_override; docker compose -f compose.yaml -f "$OVERRIDE" up -d --no-build backend >/dev/null; backend_wait ;;
  # Any plain `docker compose up` (even of another service) recreates the backend without the override, because its
  # config hash differs. Always pass the override while the suite runs; `frontend` does that for the proxy image.
  frontend) write_override; docker compose -f compose.yaml -f "$OVERRIDE" up -d --no-build frontend >/dev/null; backend_wait ;;
  stub) stub_up ;;
  down) docker rm -f qa149-stub >/dev/null 2>&1 || true; docker compose up -d --no-build backend >/dev/null; backend_wait ;;
  *) echo "usage: $0 up|restart|stub|down" >&2; exit 2 ;;
esac
