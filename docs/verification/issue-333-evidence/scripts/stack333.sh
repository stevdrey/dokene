#!/usr/bin/env bash
# ABOUTME: Suite #333 controlled provider mode: the #149 Graph API stub inside the backend's network namespace and a
# ABOUTME: compose override with a local secret source of synthetic canary tokens. Global outbound stays OFF.
#   stack333.sh up | restart | stub | down
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/qa333.sh"
. "$OUTD/ids"
cd "$WT"
STUBDIR=$QA_HOME/stub; STUBBIN=$QA_HOME/stub-bin; OVERRIDE=$QA_HOME/compose.qa333.yaml; STUB=qa333-stub
mkdir -p "$STUBDIR" "$STUBBIN"

stub_up() {
  docker rm -f "$STUB" >/dev/null 2>&1 || true
  javac --release 26 -d "$STUBBIN" docs/verification/issue-149-evidence/scripts/GraphStub.java
  printf 'A=QA333-CANARY-TOKEN-A\nB=QA333-CANARY-TOKEN-B\n' > "$STUBDIR/tokens"
  printf '100000000000001,100000000000002' > "$STUBDIR/phones.list"
  printf 'customer_name,message_body' > "$STUBDIR/params"
  docker run -d --rm --user "$(id -u):$(id -g)" --name "$STUB" --network "container:$(docker compose ps -q oidc-bridge)" \
    -v "$STUBDIR:/stub" -v "$STUBBIN:/stub-bin:ro" --entrypoint java dokene-backend:local -cp /stub-bin GraphStub >/dev/null
  sleep 1; docker logs "$STUB" 2>&1 | tail -1
}

write_override() {
  cat > "$OVERRIDE" <<EOF
# Generated by stack333.sh (suite #333). Synthetic canary values only; they exist to be searched for in DOM/logs.
services:
  backend:
    environment:
      DOKENE_INTEGRATION_SECRETS_SOURCE: local
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_SCOPE: deployment
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_REF: qa333-app-secret
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_PURPOSE: APP_SECRET
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_0_VALUE: QA333-CANARY-APP-SECRET
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_SCOPE: deployment
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_REF: qa333-verify
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_PURPOSE: WEBHOOK_VERIFY_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_1_VALUE: QA333-CANARY-VERIFY
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_SCOPE: tenant
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_TENANT_ID: $A
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_REF: qa333-token-a
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_PURPOSE: WHATSAPP_ACCESS_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_2_VALUE: QA333-CANARY-TOKEN-A
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_SCOPE: tenant
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_TENANT_ID: $B
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_REF: qa333-token-b
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_PURPOSE: WHATSAPP_ACCESS_TOKEN
      DOKENE_INTEGRATION_SECRETS_LOCAL_ENTRIES_3_VALUE: QA333-CANARY-TOKEN-B
      DOKENE_INTEGRATION_WHATSAPP_VERIFY_TOKEN_REF: qa333-verify
      DOKENE_INTEGRATION_WHATSAPP_APP_SECRET_REF: qa333-app-secret
      DOKENE_INTEGRATION_WHATSAPP_GRAPH_BASE_URL: http://127.0.0.1:18080
      DOKENE_MESSAGING_OUTBOUND_ENABLED: "${QA333_OUTBOUND:-false}"
EOF
}

backend_wait() {
  local i; for i in $(seq 1 90); do
    [ "$(curl -s -o /dev/null -w '%{http_code}' "$BFF/api/session" || true)" = 401 ] && { echo "backend up after ${i}s"; return 0; }
    sleep 1
  done
  echo "backend did not come up" >&2; return 1
}

case ${1:-} in
  up) stub_up; write_override; docker compose -f compose.yaml -f "$OVERRIDE" up -d --no-build backend >/dev/null; backend_wait ;;
  restart) write_override; docker compose -f compose.yaml -f "$OVERRIDE" up -d --no-build backend >/dev/null; backend_wait ;;
  stub) stub_up ;;
  down) docker rm -f "$STUB" >/dev/null 2>&1 || true; docker compose up -d --no-build backend >/dev/null; backend_wait ;;
  *) echo "usage: $0 up|restart|stub|down" >&2; exit 2 ;;
esac
