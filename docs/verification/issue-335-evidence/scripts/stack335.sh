#!/usr/bin/env bash
# ABOUTME: Suite #335 backend restart: the #333 controlled provider override (loopback stub, canary tokens) plus, only
# ABOUTME: while the global switch is ON, the W2 send policy overrides. A global-OFF restart always runs the baseline.
#   QA333_OUTBOUND=true|false [QA335_MIN_INTERVAL=3m QA335_CLAIM_TIMEOUT=2m QA335_RECOVERY_INTERVAL=15s] stack335.sh restart
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
. "$HERE/../../issue-333-evidence/scripts/qa333.sh"
[ "${1:-}" = restart ] || { echo "usage: $0 restart" >&2; exit 2; }
OUT=${QA333_OUTBOUND:-false}
OVR333=$QA_HOME/compose.qa333.yaml; OVR335=$QA_HOME/compose.qa335.yaml
[ -f "$OVR333" ] || { echo "missing $OVR333: run stack333.sh up first" >&2; exit 2; }
grep -q 'DOKENE_INTEGRATION_WHATSAPP_GRAPH_BASE_URL: http://127.0.0.1:18080' "$OVR333" || { echo "override is not the loopback stub" >&2; exit 2; }
sed -i "s/^\(      DOKENE_MESSAGING_OUTBOUND_ENABLED: \).*/\1\"$OUT\"/" "$OVR333"
{
  echo "# Generated by stack335.sh (suite #335). Policy overrides apply only while the global switch is ON."
  echo "services:"; echo "  backend:"; echo "    environment:"
  if [ "$OUT" = true ]; then
    [ -n "${QA335_MIN_INTERVAL:-}" ] && echo "      DOKENE_MESSAGING_MIN_CONTACT_INTERVAL: \"$QA335_MIN_INTERVAL\""
    [ -n "${QA335_CLAIM_TIMEOUT:-}" ] && echo "      DOKENE_MESSAGING_RECOVERY_CLAIM_TIMEOUT: \"$QA335_CLAIM_TIMEOUT\""
    [ -n "${QA335_RECOVERY_INTERVAL:-}" ] && echo "      DOKENE_MESSAGING_RECOVERY_INTERVAL: \"$QA335_RECOVERY_INTERVAL\""
  fi
  echo "      QA335_STACK: \"outbound=$OUT\""
} > "$OVR335"
cd "$WT"
docker compose -f compose.yaml -f "$OVR333" -f "$OVR335" up -d --no-build backend >/dev/null
for i in $(seq 1 90); do
  [ "$(curl -s -o /dev/null -w '%{http_code}' "$BFF/api/session" || true)" = 401 ] && { echo "backend up after ${i}s (outbound=$OUT)"; exit 0; }
  sleep 1
done
echo "backend did not come up" >&2; exit 1
