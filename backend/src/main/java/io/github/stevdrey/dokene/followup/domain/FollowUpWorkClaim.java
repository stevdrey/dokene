// ABOUTME: A worker's claim on one follow-up work item (issue 458, ADR 0037). The attempt number and claim token are the
// ABOUTME: fencing identity: only the current, unexpired claim may renew, complete or fail the item.
package io.github.stevdrey.dokene.followup.domain;

import io.github.stevdrey.dokene.customer.domain.CustomerId;
import io.github.stevdrey.dokene.tenant.domain.TenantId;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Objects;
import java.util.UUID;

/**
 * A claim names a candidate, never a send. The holder must re-evaluate eligibility, consent and approval before acting,
 * and a claim that was renewed is replaced by the returned claim, which carries the new lease expiry.
 *
 * @param attempt the item's attempt number for this claim, starting at 1; a later claim always has a higher one
 * @param claimToken a random token generated by PostgreSQL for this claim only
 */
public record FollowUpWorkClaim(UUID candidateId, TenantId tenantId, CustomerId customerId, LocalDate dueDate,
        FollowUpWorkerId worker, int attempt, UUID claimToken, Instant claimedAt, Instant leaseExpiresAt) {

    public FollowUpWorkClaim {
        Objects.requireNonNull(candidateId, "Candidate id is required");
        Objects.requireNonNull(tenantId, "Tenant is required");
        Objects.requireNonNull(customerId, "Customer is required");
        Objects.requireNonNull(dueDate, "Due date is required");
        Objects.requireNonNull(worker, "Worker is required");
        Objects.requireNonNull(claimToken, "Claim token is required");
        Objects.requireNonNull(claimedAt, "Claim instant is required");
        Objects.requireNonNull(leaseExpiresAt, "Lease expiry is required");
        if (attempt < 1) {
            throw new IllegalArgumentException("Claim attempt must be positive");
        }
        if (!leaseExpiresAt.isAfter(claimedAt)) {
            throw new IllegalArgumentException("A lease must expire after its claim");
        }
    }

    public FollowUpWorkClaim withLeaseExpiresAt(Instant expiresAt) {
        return new FollowUpWorkClaim(candidateId, tenantId, customerId, dueDate, worker, attempt, claimToken,
                claimedAt, expiresAt);
    }
}
